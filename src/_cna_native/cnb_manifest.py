"""ctypes manifest for CNA's ``cnb.h`` compiled-content family.

Split out of :mod:`_cna_native.loader` because it is a family of its own: 270
routes over one header, imported because ``cna.extensions.content`` projects
them, not because the XNA profile needs any of them.  Every entry is proven
against the canonical C declaration by ``tools/verify_prototypes.py``, and the
fourth column states the ownership contract the Python wrapper has to keep.

Two ``cnb.h`` routes are deliberately absent.  ``cna_cnb_checked_add`` and
``cna_cnb_checked_multiply`` exist so a C reader can combine two file-declared
64-bit values without wrapping around; Python integers are unbounded, so the
same computation is exact without them and a call would only convert an exact
answer into a narrower one.  ``_cna_native.cnb_support`` performs those bounds
checks in Python instead, at the point where a value actually has to fit a
native width.
"""

