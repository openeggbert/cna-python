#: The minimal ``content.h`` slice the CNB loader registry depends on.
#:
#: ``cna_cnb_loader_invoke`` takes a content-manager handle and **requires** it:
#: passing none is refused, because the canonical loader signature takes the
#: manager by reference and there is no "no manager" to pass.  Without these two
#: routes a registered loader can be resolved and never invoked, so the registry
#: would be surface with no capability behind it.
#:
#: Exactly create and destroy are imported.  No load route, no cache route and no
#: root-directory route is: this manager exists so a loader has the collaborator
#: its signature demands, and it shares nothing with
#: ``Microsoft.Xna.Framework.Content.ContentManager``, which stays managed XNB
#: with its own separate cache.
